/*
  Canopy: download county land values and cash rents from USDA NASS Quick Stats.

  Run once (Node 18 or newer), from the folder that holds index.html:
      NASS_KEY=your_key_here node scripts/fetch_land_values.js

  It writes land_values.js next to index.html. Commit that file to GitHub.
  Never commit your key: the script reads it from NASS_KEY so it stays off disk.
*/
const fs = require('fs');
const path = require('path');

const KEY = process.env.NASS_KEY;
if(!KEY){
  console.error('Missing key. Run: NASS_KEY=your_key_here node scripts/fetch_land_values.js');
  process.exit(1);
}

const API = 'https://quickstats.nass.usda.gov/api/api_GET/';

// Value per acre of farmland incl. buildings, every county (Census of Agriculture, every 5 years).
const VALUE_ITEM = 'AG LAND, INCL BUILDINGS - ASSET VALUE, MEASURED IN $ / ACRE';
// County cash rents (annual or every other year survey).
const RENT_ITEMS = {
  cropNonIrr: 'RENT, CASH, CROPLAND, NON-IRRIGATED - EXPENSE, MEASURED IN $ / ACRE',
  cropIrr:    'RENT, CASH, CROPLAND, IRRIGATED - EXPENSE, MEASURED IN $ / ACRE',
  pasture:    'RENT, CASH, PASTURELAND - EXPENSE, MEASURED IN $ / ACRE'
};

async function query(params){
  const qs = new URLSearchParams(Object.assign({ key: KEY, format: 'JSON', agg_level_desc: 'COUNTY' }, params));
  const res = await fetch(API + '?' + qs.toString());
  const text = await res.text();
  let body;
  try { body = JSON.parse(text); } catch(e){ throw new Error('USDA returned non-JSON (' + res.status + '): ' + text.slice(0, 200)); }
  if(body.error) throw new Error('USDA error: ' + [].concat(body.error).join('; '));
  if(!res.ok) throw new Error('USDA request failed (' + res.status + ')');
  return body.data || [];
}

// "3,846" -> 3846; "(D)" (withheld) or "(Z)" -> null
const num = v => { const n = parseFloat(String(v).replace(/,/g, '')); return isFinite(n) ? n : null; };
const fips = r => String(r.state_fips_code).padStart(2, '0') + String(r.county_code).padStart(3, '0');
const realCounty = r => r.county_code && !/^99[89]$/.test(String(r.county_code)); // 998/999 = "other counties" combined
const titleCase = s => String(s || '').toLowerCase().replace(/\b\w/g, c => c.toUpperCase());

(async () => {
  const out = {};
  const ensure = r => (out[fips(r)] = out[fips(r)] || { county: titleCase(r.county_name), state: r.state_alpha });

  console.log('Pulling county land values (Census of Agriculture)...');
  const values = await query({ source_desc: 'CENSUS', short_desc: VALUE_ITEM, domain_desc: 'TOTAL', year__GE: '2017' });
  values.filter(realCounty).forEach(r => {
    const v = num(r.Value); if(v === null) return;
    const c = ensure(r), y = Number(r.year);
    if(!c.valueYear || y > c.valueYear){ c.valuePerAcre = v; c.valueYear = y; }
  });

  for(const [field, item] of Object.entries(RENT_ITEMS)){
    console.log('Pulling county cash rents: ' + field + '...');
    let rows = [];
    try { rows = await query({ source_desc: 'SURVEY', short_desc: item, domain_desc: 'TOTAL', year__GE: '2019' }); }
    catch(err){ console.warn('  skipped: ' + err.message); continue; }
    rows.filter(realCounty).forEach(r => {
      const v = num(r.Value); if(v === null) return;
      const c = ensure(r), y = Number(r.year), yk = field + 'Year';
      if(!c[yk] || y > c[yk]){ c[field] = v; c[yk] = y; }
    });
  }

  const n = Object.keys(out).length;
  if(!n) throw new Error('No county data came back. Check the key and try again.');
  const meta = { source: 'USDA NASS Quick Stats', built: new Date().toISOString().slice(0, 10), counties: n };
  const file = path.join(__dirname, '..', 'land_values.js');
  fs.writeFileSync(file, '// Generated by scripts/fetch_land_values.js. Do not edit by hand.\n' +
    'window.LAND_VALUES = ' + JSON.stringify({ meta, counties: out }) + ';\n');
  console.log('Wrote ' + file + ' with ' + n + ' counties.');
})().catch(err => { console.error(err.message); process.exit(1); });
